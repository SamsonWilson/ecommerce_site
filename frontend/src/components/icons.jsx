// Étoiles de notation. `value` sur 5 ; la dernière étoile passe en contour si demi-point.
export function Stars({ value = 5 }) {
  const full = Math.floor(value);
  const stars = [];
  for (let i = 0; i < 5; i++) {
    const outline = i >= full;
    stars.push(
      <svg key={i} viewBox="0 0 20 20" fill={outline ? 'none' : undefined} strokeWidth={outline ? '1' : undefined}>
        <polygon points="10,1 12.6,7 19,7.5 14,12 15.5,18.5 10,15 4.5,18.5 6,12 1,7.5 7.4,7" />
      </svg>
    );
  }
  return <div className="stars">{stars}</div>;
}
